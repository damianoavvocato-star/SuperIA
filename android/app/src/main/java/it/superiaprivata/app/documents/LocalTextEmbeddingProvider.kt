package it.superiaprivata.app.documents

/**
 * Contract for a fully on-device text embedding model.
 *
 * Implementations must return finite vectors with a stable dimension for both
 * document passages and search queries. Implementations must not use a network.
 */
interface LocalTextEmbeddingProvider {
    val modelId: String
    val dimensions: Int

    suspend fun embedDocument(title: String, text: String): FloatArray
    suspend fun embedQuery(text: String): FloatArray
}

/** A passage and its already-computed local embedding. */
data class SemanticChunkVector(
    val documentTitle: String,
    val chunkNumber: Int,
    val text: String,
    val embedding: FloatArray
)

/**
 * Pure Kotlin cosine search. Embeddings are generated by LocalTextEmbeddingProvider;
 * this class deliberately has no model/runtime dependency.
 */
object SemanticVectorSearch {
    fun search(
        queryEmbedding: FloatArray,
        chunks: List<SemanticChunkVector>,
        limit: Int = 5,
        minimumScore: Float = -1f
    ): List<Pair<SemanticChunkVector, Float>> {
        require(limit > 0) { "Il numero di risultati deve essere positivo." }
        require(minimumScore in -1f..1f) { "La soglia deve essere compresa tra -1 e 1." }
        require(queryEmbedding.isNotEmpty() && queryEmbedding.all(Float::isFinite)) {
            "Embedding della query vuoto o non valido."
        }
        val queryNorm = norm(queryEmbedding)
        require(queryNorm > 0f) { "Embedding della query nullo." }

        return chunks.mapNotNull { chunk ->
            if (chunk.embedding.size != queryEmbedding.size ||
                chunk.embedding.isEmpty() ||
                !chunk.embedding.all(Float::isFinite)
            ) return@mapNotNull null
            val chunkNorm = norm(chunk.embedding)
            if (chunkNorm == 0f) return@mapNotNull null
            var dot = 0f
            for (index in queryEmbedding.indices) {
                dot += queryEmbedding[index] * chunk.embedding[index]
            }
            val score = (dot / (queryNorm * chunkNorm)).coerceIn(-1f, 1f)
            if (score >= minimumScore) chunk to score else null
        }.sortedByDescending { it.second }.take(limit)
    }

    private fun norm(vector: FloatArray): Float {
        var sum = 0f
        vector.forEach { sum += it * it }
        return kotlin.math.sqrt(sum)
    }
}
